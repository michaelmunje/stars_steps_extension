"""Rebuild ``docs/latest_forecaster/``: the reference multi-agent STARS forecaster, its per-dataset
test results and forecast figures, as a folder GitHub renders in the browser.

    python -m baselines.publish_latest_forecaster --name "Pooled, LR 3e-4" \\
        --run-dir experiments/stars_ma/runs/cvae_all_lr3e-4_seed42 \\
        --figures runs/forecaster_visuals/cvae_all_lr3e-4_seed42 \\
        --comparison docs/results/stars_ma_single_vs_all.png --decisions "84-86"

The output folder is deleted and recreated every time, so it only ever holds one version. The test
report is ``<run-dir>/eval_test_all.json`` (``evaluate_stars_ma``); figures are every PNG in
``--figures`` (e.g. ``visualize_stars_ma`` outputs named ``forecasts_<dataset>.png``). Checkpoints
are not copied (they live under ``experiments/``); the page records the path.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
from datetime import date
from pathlib import Path

from baselines.plot_stars_ma_summary import LABELS, plot

ROOT = Path(__file__).resolve().parents[2]


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "--no-optional-locks", "rev-parse", "--short", "HEAD"], cwd=ROOT,
                              capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--name", required=True)
    parser.add_argument("--run-dir", type=Path, required=True)
    parser.add_argument("--report", type=Path, help="Default: <run-dir>/eval_test_all.json")
    parser.add_argument("--figures", type=Path, help="Directory of forecast PNGs to include")
    parser.add_argument("--comparison", type=Path, help="Single-vs-pooled figure to include")
    parser.add_argument("--decisions", default="")
    parser.add_argument("--notes", default="")
    parser.add_argument("--out", type=Path, default=ROOT / "docs/latest_forecaster")
    args = parser.parse_args()
    report_path = args.report or args.run_dir / "eval_test_all.json"
    report = json.loads(report_path.read_text())
    config = json.loads((args.run_dir / "config.json").read_text())
    status = json.loads((args.run_dir / "status.json").read_text())

    shutil.rmtree(args.out, ignore_errors=True)
    (args.out / "figures").mkdir(parents=True)
    shutil.copy(report_path, args.out / "eval_test_all.json")
    plot(report, args.out / "figures" / "per_dataset.png")
    if args.comparison:
        shutil.copy(args.comparison, args.out / "figures" / "single_vs_pooled.png")
    forecasts = sorted(args.figures.glob("*.png")) if args.figures else []
    animations = sorted(args.figures.glob("*.gif")) if args.figures else []
    for path in [*forecasts, *animations]:
        shutil.copy(path, args.out / "figures" / path.name)

    tf, cv = report["teacher_forced"], report["constant_velocity"]
    closed = report.get("closed_loop", {})
    exec_key = next(iter(closed), None)
    names = report["datasets"]
    checkpoint = (args.run_dir / "checkpoints" / "best.pt")
    checkpoint = checkpoint.resolve().relative_to(ROOT) if checkpoint.resolve().is_relative_to(ROOT) else checkpoint
    lines = [f"# Latest trajectory forecaster: {args.name}", "",
             f"Published {date.today().isoformat()} from commit `{_git_commit()}`. Regenerated by "
             "`python -m baselines.publish_latest_forecaster` for every new reference model; older versions live in "
             "git history.", "", f"Checkpoint: `{checkpoint}` (best validation {status.get('best_selection', float('nan')):.4f} "
             f"at epoch {status.get('best_epoch')}).", ""]
    if args.decisions:
        lines += [f"Reasoning: [`docs/decisions.md`](../decisions.md), entries {args.decisions}.", ""]
    if args.notes:
        lines += [args.notes, ""]
    lines += ["## Test results", "",
              f"Test split, best-of-{report.get('k', 20)} for the CVAE, in metres. *Moving* = agents whose true future "
              "mean speed is above 0.2 m/s." + (f" *Rollout* = re-forecasting from its own predictions every "
              f"{exec_key.split('_')[1]} model steps." if exec_key else ""), "",
              "| Dataset | Agent ADE / FDE | Moving ADE / FDE | Joint ADE | Constant velocity ADE / FDE |"
              + (" Rollout ADE |" if exec_key else ""),
              "| --- | --- | --- | --- | --- |" + (" --- |" if exec_key else "")]
    for n in names:
        g = lambda d, k: d.get(f"{n}/{k}", float("nan"))
        row = (f"| {LABELS.get(n, n)} | {g(tf, 'agent_ade'):.3f} / {g(tf, 'agent_fde'):.3f} | "
               f"{g(tf, 'moving_ade'):.3f} / {g(tf, 'moving_fde'):.3f} | {g(tf, 'joint_ade'):.3f} | "
               f"{g(cv, 'agent_ade'):.3f} / {g(cv, 'agent_fde'):.3f} |")
        if exec_key:
            row += f" {g(closed[exec_key], 'agent_ade'):.3f} |"
        lines.append(row)
    lines += ["", "![Per-dataset test error](figures/per_dataset.png)", ""]
    if args.comparison:
        lines += ["## Against one model per dataset", "", "![single vs pooled](figures/single_vs_pooled.png)", ""]
    if forecasts:
        lines += ["## Forecasts", "",
                  "Test windows with the most moving pedestrians (at most 10 people, for legibility). Thick: observed "
                  "3.2 s; dashed: ground truth 4.8 s; thin: STARS samples; dotted grey: constant velocity. The "
                  "animations first build up the observed history, then unroll the 4.8 s forecast step by step "
                  "(one frame per 0.4 s step).", ""]
        for path in forecasts:
            dataset = path.stem.removeprefix("forecasts_")
            lines += [f"### {LABELS.get(dataset, dataset)}", ""]
            lines += [f"![{gif.stem}](figures/{gif.name})" for gif in animations if gif.stem.startswith(path.stem + "_")]
            lines += ["", f"![{path.stem}](figures/{path.name})", ""]
    datasets = config.get("datasets") or [e["name"] for e in config.get("train_entries", [])]
    lines += ["## Recipe", "", "```yaml", *(f"{k}: {config.get(k)}" for k in
              ("config", "decoder", "cvae_latent_dim", "encoder_mode", "knn", "radius", "kl_weight", "learning_rate",
               "weight_decay", "dropout", "decoder_dropout", "decoder_hidden_dim", "warmup_epochs", "max_nodes",
               "epochs", "seed")), "```", "",
              "Evaluate it:", "", "```bash",
              f"python -m baselines.evaluate_stars_ma --checkpoint {checkpoint} --config configs/stars_ma/all.yaml \\",
              "  --split test --device cuda --output eval_test_all.json", "```", ""]
    (args.out / "README.md").write_text("\n".join(lines))
    print(args.out / "README.md")


if __name__ == "__main__":
    main()
